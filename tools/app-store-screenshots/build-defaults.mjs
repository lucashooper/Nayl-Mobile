// Regenerates defaults.js from the images in default-screens/.
// The images are inlined as data URLs so index.html works when opened
// straight from disk (file:// images would otherwise taint the export canvas).
//
//   node tools/app-store-screenshots/build-defaults.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'default-screens');
const mime = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };

const entries = readdirSync(dir)
  .filter((f) => mime[extname(f).toLowerCase()])
  .sort()
  .map((f) => {
    const data = readFileSync(join(dir, f)).toString('base64');
    return `  ${JSON.stringify(basename(f, extname(f)))}: 'data:${mime[extname(f).toLowerCase()]};base64,${data}'`;
  });

writeFileSync(
  join(here, 'defaults.js'),
  `// Generated by build-defaults.mjs. Do not edit by hand.\nwindow.DEFAULT_SCREENS = {\n${entries.join(',\n')}\n};\n`,
);
console.log(`Wrote ${entries.length} default screens to defaults.js`);
